export const CHAR_WIDTH = 6;
export const CHAR_HEIGHT = 7;

/** Measure pixel width of a single line of text. */
export function measureText(text, scale = 1) {
  if (!text) return 0;
  return Math.max(0, text.length * CHAR_WIDTH * scale - scale);
}

/**
 * Render crisp pixel text onto the canvas.
 * Supports optional 1px GBA drop shadow and horizontal alignment.
 */
export function drawText(
  ctx,
  text,
  x,
  y,
  {
    color = '#383838',
    shadow = null,
    scale = 1,
    align = 'left',
  } = {}
) {
  if (!text) return;
  const str = String(text);
  let startX = Math.round(x);
  const startY = Math.round(y);

  if (align === 'center') {
    startX = Math.round(x - measureText(str, scale) / 2);
  } else if (align === 'right') {
    startX = Math.round(x - measureText(str, scale));
  }

  const drawPass = (ox, oy, fill) => {
    ctx.fillStyle = fill;
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      const glyph = GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
      const gx = startX + i * CHAR_WIDTH * scale + ox;
      for (let row = 0; row < 7; row++) {
        const line = glyph[row];
        for (let col = 0; col < 5; col++) {
          if (line[col] === '#') {
            ctx.fillRect(gx + col * scale, startY + row * scale + oy, scale, scale);
          }
        }
      }
    }
  };

  if (shadow) {
    drawPass(scale, scale, shadow);
  }
  drawPass(0, 0, color);
}

/**
 * Word-wrap text into lines that fit within `maxChars` columns.
 * Honors explicit newline characters.
 */
export function wrapText(text, maxChars = 35) {
  const paragraphs = String(text).split('\n');
  const lines = [];

  for (const para of paragraphs) {
    const words = para.split(' ');
    let current = '';

    for (const word of words) {
      if (!current) {
        current = word;
      } else if (current.length + 1 + word.length <= maxChars) {
        current += ' ' + word;
      } else {
        lines.push(current);
        current = word;
      }
    }
    lines.push(current);
  }

  return lines;
}

/**
 * Draw an authentic HD-2D rounded double-bordered handheld UI window frame
 * with subtle drop shadow and top bevel sheen.
 */
export function drawGbaBox(
  ctx,
  x,
  y,
  w,
  h,
  {
    fill = '#FAFBFD',
    outerBorder = '#1E2634',
    accentBorder = '#4C86A8',
    accentHighlight = '#7BB6D8',
    innerBorder = '#304054',
    shadow = true,
  } = {}
) {
  x = Math.round(x);
  y = Math.round(y);
  w = Math.round(w);
  h = Math.round(h);

  // Soft elevation drop shadow
  if (shadow) {
    ctx.fillStyle = 'rgba(8, 12, 24, 0.34)';
    ctx.fillRect(x + 3, y + 4, w - 2, h);
    ctx.fillRect(x + 2, y + 5, w, h - 2);
  }

  // Outer rounded silhouette (2px chamfered corners)
  ctx.fillStyle = outerBorder;
  ctx.fillRect(x + 2, y, w - 4, h);
  ctx.fillRect(x + 1, y + 1, w - 2, h - 2);
  ctx.fillRect(x, y + 2, w, h - 4);

  // Colored double-frame accent trim
  ctx.fillStyle = accentBorder;
  ctx.fillRect(x + 2, y + 2, w - 4, h - 4);
  ctx.fillRect(x + 1, y + 3, w - 2, h - 6);

  // Subtle top bevel highlight along accent frame
  ctx.fillStyle = accentHighlight;
  ctx.fillRect(x + 3, y + 2, w - 6, 1);

  // Inner dark crisp rim
  ctx.fillStyle = innerBorder;
  ctx.fillRect(x + 4, y + 4, w - 8, h - 8);

  // Inner crisp paper fill
  ctx.fillStyle = fill;
  ctx.fillRect(x + 5, y + 5, w - 10, h - 10);

  // Subtle inner corner dots
  ctx.fillStyle = '#D4DCE6';
  ctx.fillRect(x + 5, y + 5, 2, 2);
  ctx.fillRect(x + w - 7, y + 5, 2, 2);
  ctx.fillRect(x + 5, y + h - 7, 2, 2);
  ctx.fillRect(x + w - 7, y + h - 7, 2, 2);
}
